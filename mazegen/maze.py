import random as r

class Maze:
    """
    A class used to represent a maze.

    Attributes:
        __rows (int): Number of rows in the maze
        __cols (int): Number of columns in the maze
        __directions (list): List of directions to move in
        __start (tuple): Start position of the maze
        __end (tuple): End position of the maze
        __map (list): 2D list representing the maze

    Methods:
        __validate_node(y: int, x: int) -> bool: Checks if a node is valid
        __dfs(): Generates the maze using depth-first search
        __bfs(): Finds the longest path in the maze using breadth-first search
        __randomise(): Randomly adds spaces to the maze edges
        generate_maze(): Generates the maze
        output_maze(filepath: str): Outputs the maze to the given file
    """

    def __init__(self, rows: int, cols: int) -> None:
        """
        Constructor for the Maze class.

        Args:
            rows (int): Number of rows in the maze
            cols (int): Number of columns in the maze
        """
        self.__rows = rows
        self.__cols = cols

        # Right, Left, Up, Down
        self.__directions = [(0, 2), (0, -2), (2, 0), (-2, 0)]

        # Generates a random start position and sets end to placeholder
        self.__start = (r.randint(0, rows - 1), r.randint(0, cols - 1))
        self.__end = self.__start

        # Produce our maze so we always start on a space
        chars = [" ", "#"] if self.__start[1] % 2 == 0 else ["#", " "]

        # Creates maze with walls of width 1 surrounding single spaces
        self.__map = [[chars[j % 2] if i % 2 == self.__start[0] %
                       2 else "#" for j in range(cols)] for i in range(rows)]

    def __valid_node(self, y: int, x: int) -> bool:
        """
        Checks if a node is a valid DFS node.

        Args:
            y (int): Row of the node
            x (int): Column of the node

        Returns:
            bool: True if node is valid, False otherwise
        """
        if not (0 <= x < self.__cols and 0 <= y < self.__rows):
            return False

        # Check that all visitable cells are walls excluding cell itself
        for i in range(max(0, y - 1), min(self.__rows, y + 2)):
            for j in range(max(0, x - 1), min(self.__cols, x + 2)):
                # Ignore diagonals
                if abs(y - i) + abs(x - j) == 1 and self.__map[i][j] == " ":
                    return False

        return True

    def __dfs(self) -> None:
        """
        Forms the maze using recursive backtracking (depth-first search). The 
        maze is generated by visiting random neighbours of the current cell and
        knocking down walls between them. The algorithm continues until all
        cells have been visited. It also stores the furthest cell from the start.
        """
        # Stack to keep track of visited cells
        stack = [self.__start]

        # Probability of popping random cell from stack, increases with maze size
        probability = 2 * (self.__rows + self.__cols) / 1000

        # Distance map for storing all distances from start for path lengths
        distances = [[-1 for j in range(self.__cols)]
                     for i in range(self.__rows)]
        distances[self.__start[0]][self.__start[1]] = 0
        max_distance = 0

        while len(stack) > 0:
            # Pop the current or a random cell from the stack to decrease corridor length
            if r.random() <= probability:
                current = stack.pop(r.randint(0, len(stack) - 1))
            else:
                current = stack.pop()

            # Pick a random neighbour to visit
            r.shuffle(self.__directions)

            for direction in self.__directions:
                new_y, new_x = current[0] + direction[0], current[1] + direction[1]

                # Check if the neighbour has all its walls up
                if self.__valid_node(new_y, new_x):

                    # Knock down the wall between current neighbour
                    self.__map[current[0] + direction[0] // 2][current[1] + direction[1] // 2] = " "

                    # Push neighbour onto stack
                    stack.append((new_y, new_x))

                    # Update distance map
                    distance = distances[current[0]][current[1]] + 1
                    distances[new_y][new_x] = distance

                    # Set end to new furthest node if applicable
                    if distance > max_distance:
                        max_distance = distance
                        self.__end = (new_y, new_x)

    def __bfs(self) -> None:
        """
        Performs a breadth-first search to find the longest path in the maze to
        set the final start and end points. The algorithm starts from the furthest
        node from the start and visits all nodes in the maze to find the diameter
        of the maze/tree.
        """
        # Start BFS from the furthest node from start
        self.__start = self.__end
        queue = [self.__start]

        # New distances matrix for BFS
        distances = [[-1 for j in range(self.__cols)]
                     for i in range(self.__rows)]
        distances[self.__start[0]][self.__start[1]] = 0
        max_distance = 0

        # Record all visited nodes
        visited = [[False for j in range(self.__cols)]
                   for i in range(self.__rows)]
        visited[self.__start[0]][self.__start[1]] = True

        while len(queue) > 0:
            current = queue.pop(0)

            for direction in [(0, 1), (0, -1), (1, 0), (-1, 0)]:
                new_y, new_x = current[0] + direction[0], current[1] + direction[1]

                # Check within bounds and that cell is space then, if unvisited, visit
                if not (0 <= new_x < self.__cols and 0 <= new_y < self.__rows):
                    continue
                elif self.__map[new_y][new_x] == " " and not visited[new_y][new_x]:
                    visited[new_y][new_x] = True
                    queue.append((new_y, new_x))
                    distances[new_y][new_x] = distances[current[0]][current[1]] + 1

                    if distances[new_y][new_x] > max_distance:
                        max_distance = distances[new_y][new_x]
                        self.__end = (new_y, new_x)

    def __randomise(self) -> None:
        """
        Randomly adds spaces to the edges of the maze to make it appear more unique.
        """
        for i in range(self.__rows):
            for j in range(self.__cols):
                if (j == 0 or j == self.__cols - 1 or i == 0 or i == self.__rows - 1) and self.__map[i][j] == "#":
                    # 2/3 chance of being a wall to avoid too many open spaces
                    self.__map[i][j] = r.choice(["#", "#", " "])

    def generate_maze(self) -> None:
        """
        Generates a maze by first using depth-first search to create a perfect
        maze and then using breadth-first search to find the longest path in the
        maze to set the final start and end points. Spaces are then randomly added
        to the edges of the maze to make it appear more random.
        """
        self.__dfs()
        self.__bfs()
        self.__randomise()

    def output_maze(self, filepath: str) -> None:
        """
        Outputs the maze to the given file.

        Args:
            filepath (str): Path to the file to write the maze to
        """
        # Add start and end points to the maze itself
        self.__map[self.__start[0]][self.__start[1]] = "S"
        self.__map[self.__end[0]][self.__end[1]] = "E"

        try:
            with open(filepath, "w") as file:
                for row in self.__map:
                    file.write("".join(row) + "\n")

            print(f"Maze written to {filepath}")
        except IOError:
            print("Error: Could not write to file")
